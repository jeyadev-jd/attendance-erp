// Semesters, served from Supabase over HTTPS.
//
// Mounted at /api/v2/semesters alongside the Prisma/D1 router at /api/semesters.
// Logic, guards, status codes and response shapes unchanged.
import { Hono } from "hono";
import { HTTPException } from "hono/http-exception";
import type { AppEnv } from "../types";
import { roleGuard } from "../middleware/roleGuard";
import { requireSupabase } from "../middleware/supabase";
import {
  createSemesterSchema,
  updateSemesterSchema,
  cloneSemesterSchema,
} from "../schemas/semesters";
import * as repo from "@attendance/db/repos/semesters";
import * as yearRepo from "@attendance/db/repos/academicYears";
import type { SupabaseClient } from "@supabase/supabase-js";

const semesters = new Hono<AppEnv>();
const canManage = roleGuard("SUPER_ADMIN", "ADMIN");

/** Mirrors the assertAcademicYearInOrg guard in the Prisma router, including its 404. */
async function assertAcademicYearInOrg(
  db: SupabaseClient,
  academicYearId: string,
  organizationId: string
) {
  const year = await yearRepo.findInOrg(db, academicYearId, organizationId);
  if (!year) throw new HTTPException(404, { message: "Academic year not found" });
  return year;
}

semesters.get("/", async (c) => {
  const db = requireSupabase(c);
  const user = c.get("user");
  return c.json(
    await repo.listByOrg(db, user.organizationId, c.req.query("academicYearId"))
  );
});

semesters.get("/:id", async (c) => {
  const db = requireSupabase(c);
  const user = c.get("user");
  const semester = await repo.findWithSections(db, c.req.param("id"), user.organizationId);
  if (!semester) throw new HTTPException(404, { message: "Semester not found" });
  return c.json(semester);
});

semesters.post("/", canManage, async (c) => {
  const body = createSemesterSchema.parse(await c.req.json());
  const db = requireSupabase(c);
  const user = c.get("user");

  await assertAcademicYearInOrg(db, body.academicYearId, user.organizationId);

  const semester = await repo.create(db, {
    academicYearId: body.academicYearId,
    name: body.name,
    startDate: `${body.startDate}T00:00:00.000Z`,
    endDate: `${body.endDate}T00:00:00.000Z`,
    minAttendancePct: body.minAttendancePct,
    status: "UPCOMING",
  });
  return c.json(semester, 201);
});

semesters.put("/:id", canManage, async (c) => {
  const body = updateSemesterSchema.parse(await c.req.json());
  const db = requireSupabase(c);
  const user = c.get("user");
  const id = c.req.param("id");

  const existing = await repo.findInOrg(db, id, user.organizationId);
  if (!existing) throw new HTTPException(404, { message: "Semester not found" });

  return c.json(
    await repo.update(db, id, {
      ...body,
      ...(body.startDate ? { startDate: `${body.startDate}T00:00:00.000Z` } : {}),
      ...(body.endDate ? { endDate: `${body.endDate}T00:00:00.000Z` } : {}),
    })
  );
});

/**
 * Archives a semester: all its data (calendar, timetable, attendance, audit logs)
 * remains untouched and read-only — nothing is deleted or mutated except the status flag.
 */
semesters.post("/:id/archive", canManage, async (c) => {
  const db = requireSupabase(c);
  const user = c.get("user");
  const id = c.req.param("id");

  const existing = await repo.findInOrg(db, id, user.organizationId);
  if (!existing) throw new HTTPException(404, { message: "Semester not found" });
  if (existing.status === "ARCHIVED") {
    throw new HTTPException(409, { message: "Semester is already archived" });
  }

  return c.json(await repo.update(db, id, { status: "ARCHIVED" }));
});

/**
 * Clones the structural setup of a semester into a brand-new one: sections
 * (per department), hour configs, and timetable entries. Deliberately does
 * NOT copy calendar days, attendance, audit logs, or student enrollment.
 */
semesters.post("/:id/clone", canManage, async (c) => {
  const body = cloneSemesterSchema.parse(await c.req.json());
  const db = requireSupabase(c);
  const user = c.get("user");
  const sourceId = c.req.param("id");

  // Source plus its three child collections in one request, via embeds.
  const source = await repo.findCloneSource(db, sourceId, user.organizationId);
  if (!source) throw new HTTPException(404, { message: "Source semester not found" });

  const academicYearId = body.academicYearId ?? source.academicYearId;
  await assertAcademicYearInOrg(db, academicYearId, user.organizationId);

  // Sequential stages with a compensating delete, unchanged from the D1 version:
  // each stage needs ids generated by the previous one (semester -> sections ->
  // timetable). PostgREST has no interactive transaction either, so deleting the new
  // semester on failure still stands in for a rollback — the cascade removes anything
  // already written. Each stage is now ONE batched insert rather than N single
  // creates, so there are fewer partial states to unwind than before.
  const newSemester = await repo.create(db, {
    academicYearId,
    name: body.name,
    startDate: `${body.startDate}T00:00:00.000Z`,
    endDate: `${body.endDate}T00:00:00.000Z`,
    minAttendancePct: source.minAttendancePct,
    status: "UPCOMING",
    clonedFromId: source.id,
  });

  try {
    const sectionIdMap = await repo.cloneSections(db, newSemester.id, source.sections);
    const hourConfigsCopied = await repo.cloneHourConfigs(
      db,
      newSemester.id,
      source.hour_configs
    );
    const timetablesCopied = await repo.cloneTimetables(
      db,
      newSemester.id,
      source.timetables,
      sectionIdMap
    );

    return c.json(
      {
        semester: newSemester,
        sectionsCopied: sectionIdMap.size,
        hourConfigsCopied,
        timetablesCopied,
      },
      201
    );
  } catch (err) {
    await repo.remove(db, newSemester.id).catch(() => {});
    throw err;
  }
});

export default semesters;
