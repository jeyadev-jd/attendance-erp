// Dumps the local Postgres database to SQLite-compatible INSERT statements for D1.
//
// Reads through the Postgres schema backup (the live schema.prisma now targets
// SQLite), so this must run against the Postgres DATABASE_URL.
//
// Usage:
//   DATABASE_URL="postgresql://..." node export-to-d1.mjs > d1-seed.sql
import pg from "pg";

const { Client } = pg;
const client = new Client({ connectionString: process.env.DATABASE_URL });
await client.connect();

// Parent-before-child: every table's foreign keys must already exist when it loads.
const TABLES = [
  "organizations",
  "academic_years",
  "semesters",
  "departments",
  "sections",
  "subjects",
  "users",
  "students",
  "faculty",
  "calendar_days",
  "hour_overrides",
  "hour_configs",
  "timetables",
  "timetable_overrides",
  "attendance",
  "audit_logs",
  "settings",
  "bunk_flags",
  "health_scores",
  "notifications",
];

function toSqlLiteral(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return String(value);
  // SQLite has no boolean type — Prisma reads 1/0 back as booleans.
  if (typeof value === "boolean") return value ? "1" : "0";
  if (value instanceof Date) return `'${value.toISOString()}'`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

const out = [];
out.push("-- Generated by export-to-d1.mjs — local Postgres snapshot for Cloudflare D1.");
out.push("PRAGMA defer_foreign_keys = TRUE;");

for (const table of TABLES) {
  const { rows } = await client.query(`SELECT * FROM "${table}"`);
  if (rows.length === 0) continue;

  const columns = Object.keys(rows[0]);
  const columnList = columns.map((c) => `"${c}"`).join(", ");

  out.push(`\n-- ${table} (${rows.length} rows)`);
  for (const row of rows) {
    const values = columns.map((c) => toSqlLiteral(row[c])).join(", ");
    out.push(`INSERT INTO "${table}" (${columnList}) VALUES (${values});`);
  }
}

console.log(out.join("\n"));
await client.end();
